const assert=require('node:assert/strict'),E=require('../extension/engine.js');
const p={name:'Example User',years:8,skill_years:{python:3},work_history:[{company:'A',title:'Engineer',start_date:'2020-03-01'},{company:'B'}],education:[{school:'University',degree:'BSc'}],work_authorization_country:'India',authorized_to_work:'yes',sponsorship_now:'no',sponsorship_future:'yes'};
assert.equal(E.answerFor('firstName',p).value,'Example');
assert.equal(E.answerFor('Employer name',p,{section:'work',index:1}).value,'B');
assert.equal(E.answerFor('School',p,{section:'education',index:0}).value,'University');
assert.equal(E.answerFor('Start month',p,{section:'work',index:0}).value,'03');
assert.equal(E.choice('03',[{label:'March',value:'march'}],'month').value,'march');
assert.equal(E.answerFor('Years of Python experience',p).value,3);
assert.equal(E.answerFor('Years of Java experience',p),null);
assert.equal(E.answerFor('Total years of experience',p).value,8);
assert.equal(E.answerFor('Are you legally authorized to work in India?',p).value,true);
assert.equal(E.answerFor('Are you legally authorized to work in the US?',p),null);
assert.equal(E.answerFor('Require sponsorship now or in the future?',p).value,true);
assert.equal(E.answerFor('Do you require sponsorship now?',p).value,false);
assert.equal(E.interactiveCaptcha([{visible:true,src:'https://recaptcha/size=invisible',width:300,height:80}]),false);
assert.equal(E.interactiveCaptcha([{visible:true,src:'https://recaptcha/anchor',width:304,height:78}]),true);
assert.equal(E.interactiveCaptcha([{visible:true,src:'https://recaptcha/bframe',width:304,height:400}],true),false);
assert.equal(E.actionFor({captcha:true,submit:true,managed:true,autoSubmit:true}),'awaiting_captcha');
console.log('PASS: work/education facts, skill experience, explicit eligibility and CAPTCHA detection.');
